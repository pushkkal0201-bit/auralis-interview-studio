// Run with Playwright installed in a developer environment, not required by app users.
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||undefined,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.APP_URL||'http://127.0.0.1:8765');
 await page.getByRole('button',{name:'Use sample CV & job'}).click();
 await page.getByRole('button',{name:'Build interview plan',exact:true}).click();
 await page.getByRole('button',{name:'Start interview',exact:true}).waitFor();
 await page.getByRole('button',{name:'Start interview',exact:true}).click();
 await page.locator('#answer').fill('I check whether the booking already exists.');
 await page.getByRole('button',{name:'Submit answer',exact:true}).click();
 await page.locator('#turn-count').filter({hasText:'1 answer'}).waitFor();
 await page.locator('#answer').fill('How many users should the system support?');
 await page.getByRole('button',{name:'Ask a clarification',exact:true}).click();
 await page.locator('#interviewer-reply').filter({hasText:'Scenario facts'}).waitFor();
 await page.getByRole('button',{name:'Finish & assess',exact:true}).click();
 await page.locator('#report-content').filter({hasText:'Scripted demonstration report'}).waitFor();
 await page.locator('#full-replay > summary').click();
 await page.getByRole('button',{name:'Try a new scenario',exact:true}).first().click();
 await page.locator('#retry-answer').fill('I would use a unique constraint and transaction, then test simultaneous writes.');
 await page.getByRole('button',{name:'Compare attempts',exact:true}).click();
 await page.locator('#retry-feedback').filter({hasText:'Both attempts were saved'}).waitFor();
 await page.screenshot({path:process.env.SHOT_DIR+'/report-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Interview setup',exact:true}).click();
 await page.screenshot({path:process.env.SHOT_DIR+'/setup-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Session history',exact:true}).click();
 await page.getByRole('button',{name:'Open session',exact:true}).first().waitFor();
 page.once('dialog',d=>d.accept());
 await page.getByRole('button',{name:'Delete session',exact:true}).first().click();
 await page.getByText('No saved interviews yet.').waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Interview setup',exact:true}).click();
 await page.screenshot({path:process.env.SHOT_DIR+'/setup-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw new Error('Mobile horizontal overflow');
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('Browser workflow passed: setup, answer, clarification, assessment, retry, history, deletion, responsive layout.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
